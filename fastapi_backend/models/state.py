"""
LangGraph 对话状态契约定义 (AgentState)
作为整个客服多智能体工作流的状态总线 (State Schema)，
负责在各个 Graph 节点（意图识别、Qdrant检索、记忆合成、DeepSeek生成、人工升级）之间传递与累积上下文数据。
"""

from typing import TypedDict, List, Dict, Any, Optional


class AgentState(TypedDict):
    # ==================== 1. 会话元数据 ====================
    session_id: str
    """
    【会话唯一标识符】
    - 作用：全局追踪当前客户对话线程，对应 LangGraph 中的 thread_id 以及持久化 Checkpointer。
    - 示例："sess_1711800000_u901"
    """

    user_message: str
    """
    【客户本轮原始输入消息】
    - 作用：作为本轮工作流的触发源，供意图识别、情绪分析与 BGE-M3 向量检索使用。
    - 示例："我的黄金会员退货免运费怎么申请？"
    """

    # ==================== 2. 意图与情绪判定 ====================
    intent: str
    """
    【售后业务意图分类】
    - 作用：由 analyze_query_node 识别，用于精准定位业务领域、指引提示词模板选择或路由到专项坐席组。
    - 常见枚举："7天无理由退货政策"、"特殊不可退换商品范围"、"退货运费承担与会员权益"、"退款质检与到账时效" 等。
    """

    sentiment: str
    """
    【客户情绪感知状态】
    - 作用：评估用户当前的情绪极性，用于负向情绪拦截与体验风控。
    - 常见枚举："positive" (积极/满意)、"neutral" (客观平静)、"frustrated" (烦躁/愤怒/催单)。
    """

    explicit_human_request: bool
    """
    【显式转人工指令标记】
    - 作用：检测用户输入中是否包含“转人工”、“投诉”、“找主管”等强指令关键词。
    - 路由意义：若为 True，Graph 条件分支会直接跳过 RAG 检索与大模型生成，无缝跳转到人工坐席接管节点。
    """

    # ==================== 3. Qdrant 向量召回结果 ====================
    retrieved_docs: List[Dict[str, Any]]
    """
    【知识库召回的切片文档列表】
    - 作用：由 qdrant_retrieve_node 通过 BGE-M3 (1024维) 检索召回的 FAQ 条款切片。
    - 包含字段：id, title, content, tags, category 等，作为上下文证据注入给 DeepSeek。
    """

    top_similarity_score: float
    """
    【知识召回最高余弦相似度得分】
    - 作用：衡量知识库中最匹配条款与用户问题的相关度（取值区间 0.0 ~ 1.0）。
    - 风控阈值：若低于系统预设阈值（如 settings.SIMILARITY_THRESHOLD = 0.50），可触发低置信度防幻觉机制并转人工。
    """

    # ==================== 4. 客户画像与长期记忆 ====================
    user_profile: Dict[str, Any]
    """
    【客户画像与特权数据】
    - 作用：从会话或用户中台拉取的会员信息（如会员等级 tier、昵称、历史客单价、累计退换次数）。
    - 业务价值：供大模型做针对性回答（例如告知黄金会员“您享有每月 3 次平台补贴免运费”）。
    """

    summary_memory: str
    """
    【多轮历史对话摘要记忆】
    - 作用：由 MemoryService 维护的多轮会话长程摘要压缩，解决长对话超出 Token 上下文窗口的问题。
    - 示例："用户此前咨询了鞋子尺码不合适想退货，已为其核验为黄金会员资格。"
    """

    # ==================== 5. 提示词装配与大模型回复 ====================
    assembled_prompt: str
    """
    【动态装配后的最终 Prompt】
    - 作用：由 memory_synthesis_node 将用户画像、多轮摘要、知识库条款与当前提问融合后的完整提示词。
    - 价值：用于开发调试、审计模型输入、排查 Prompt 拼接质量问题。
    """

    generated_response: str
    """
    【大模型/客服系统生成的最终答复文本】
    - 作用：由 deepseek_generate_node（或降级/人工接管节点）产出的面向客户的最终回答。
    - 示例："尊敬的黄金会员，针对您咨询的退货免运费权益..."
    """

    # ==================== 6. 人工介入与风控标记 ====================
    escalated_to_human: bool
    """
    【是否触发人工坐席接管】
    - 作用：标记当前会话是否需要移交人工坐席介入。
    - 触发条件：用户明确呼叫人工、负向情绪严重、或知识库相似度过低导致防幻觉拦截。
    """

    escalation_reason: str
    """
    【人工介入原因说明】
    - 作用：记录为何转人工（如“客户主动要求转人工客服”、“Qdrant 向量匹配得分较低 (< 0.50)”）。
    - 价值：供人工坐席在工单工作台上一眼了解接管原因，迅速跟进处置。
    """

    # ==================== 7. 通用业务事实与中台数据槽位 (方案1: 实体解耦) ====================
    business_facts_text: Optional[str]
    """
    【通用业务事实上下文 (Business Facts Slot)】
    - 方案1核心：不论未来扩展订单、发票、积分、优惠券，所有中台事实汇总在此槽位注入 Prompt，Prompt 终身免维护。
    - 示例："【关联订单事实】\n- 订单编号：ORD-2026-88992\n- 状态：已签收..."
    """

    business_facts_list: Optional[List[Dict[str, Any]]]
    """
    【结构化业务实体对象列表】
    - 作用：存放提取到的业务对象（订单、优惠券等），供前端渲染卡片或持久化。
    """

    queried_order: Optional[Dict[str, Any]]
    """
    【特定关联订单对象 (向下兼容)】
    """

    order_query_info: Optional[str]
    """
    【特定订单摘要 (向下兼容)】
    """

    # ==================== 8. 全链路追踪 ====================
    step_trace: List[Dict[str, Any]]
    """
    【状态机执行链路追踪日志】
    - 作用：记录当前请求在 Graph 各节点流转的审计流水（Node名称、耗时 durationMs、描述、状态 success/warning/error）。
    - 价值：直接透传给前端在右侧监控面板或调试器中以可视化瀑布流呈现，实现端到端透明可观测性。
    """
